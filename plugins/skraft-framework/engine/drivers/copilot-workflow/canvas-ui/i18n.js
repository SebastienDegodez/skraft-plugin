/** @returns {Language} */
export const languageOf = (languages) => (String(languages?.[0] ?? '').toLowerCase().startsWith('fr') ? 'fr' : 'en')

/** @param {Language} language */
export const dictionary = (language) => (language === 'fr' ? FR : EN)

/** @param {Language} language @param {string} key @param {Record<string, unknown>} [params] */
export const ui = (language, key, params) => format(dictionary(language).ui[key] ?? key, params)
