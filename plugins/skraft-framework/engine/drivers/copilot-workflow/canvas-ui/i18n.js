/**
 * Replaces each `{name}` by its parameter.
 * @param {string} template @param {Record<string, unknown>} [params]
 */
export const format = (template, params = {}) => template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''))

