// <FlowFigure flow="deliver" />: a skraft flow figure in a Docusaurus page. The SVG is rendered
// at build time (render is pure, so it is in the static HTML), the animation starts in the browser.
import React, { useEffect, useMemo, useRef } from 'react'
import useDocusaurusContext from '@docusaurus/useDocusaurusContext'
import { renderFigure } from '@skraft/flow-figure/render.mjs'
import { animate } from '@skraft/flow-figure/animate.mjs'
import '@skraft/flow-figure/flow-figure.css'
import deliver from '@skraft/flows/deliver.json'

/** The flows a page may name; docs/flows/<id>.json, generated by eng/docs/flow-from-dot.mjs. */
const FLOWS = { deliver }

export default function FlowFigure({ flow }) {
  const { i18n } = useDocusaurusContext()
  const lang = i18n.currentLocale.startsWith('fr') ? 'fr' : 'en'
  const data = FLOWS[flow]
  const html = useMemo(() => renderFigure(data, { lang, embedData: false }), [data, lang])
  const host = useRef(null)
  useEffect(() => {
    const figure = host.current?.querySelector('figure.skraft-flow')
    if (!figure) return undefined
    const controller = animate(figure, data)
    return () => controller.destroy()
  }, [html, data])
  return <div ref={host} dangerouslySetInnerHTML={{ __html: html }} />
}
